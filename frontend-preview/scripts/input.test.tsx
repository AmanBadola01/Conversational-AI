import {JSDOM} from 'jsdom';
import assert from 'node:assert/strict';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'https://preview.test'});
for(const key of ['window','document','navigator','HTMLElement','HTMLTextAreaElement','File','MouseEvent','KeyboardEvent'])Object.defineProperty(globalThis,key,{configurable:true,value:(dom.window as any)[key]});
globalThis.requestAnimationFrame=cb=>setTimeout(()=>cb(0),0) as unknown as number;
globalThis.cancelAnimationFrame=id=>clearTimeout(id);
let counter=0;const revoked:string[]=[];
URL.createObjectURL=()=>`blob:preview-${++counter}`;URL.revokeObjectURL=url=>revoked.push(url);
const React=await import('react');
const {render,fireEvent,cleanup}=await import('@testing-library/react');
const {PromptInput}=await import('../components/ui/ai-chat-input');
const submissions:any[]=[];
const ui=render(<PromptInput maxAttachments={2} onSubmit={(...args)=>submissions.push(args)}/>);
fireEvent.click(ui.getByRole('button',{name:'Open prompt input'}));
const text=ui.getByRole('textbox',{name:'Prompt'});
fireEvent.change(text,{target:{value:'Remember Atlas'}});
fireEvent.click(ui.getByRole('button',{name:'Select persona. Current: Strategy partner'}));
fireEvent.click(ui.getByRole('option',{name:'Research analyst'}));
fireEvent.change(ui.getByRole('combobox',{name:'Memory technique'}),{target:{value:'Entity memory'}});
fireEvent.keyDown(text,{key:'Enter',shiftKey:true});assert.equal(submissions.length,0);
fireEvent.keyDown(text,{key:'Enter'});assert.equal(submissions[0][0],'Remember Atlas');assert.equal(submissions[0][1].persona,'Research analyst');assert.equal(submissions[0][1].memoryTechnique,'Entity memory');
fireEvent.click(ui.getByRole('button',{name:'Open prompt input'}));
const files=[new File(['a'],'a.png',{type:'image/png'}),new File(['b'],'b.png',{type:'image/png'}),new File(['c'],'c.png',{type:'image/png'})];
fireEvent.change(ui.container.querySelector('input[type=file]')!,{target:{files}});
assert.equal(ui.getAllByRole('button',{name:/Open preview/}).length,2);
assert.equal(revoked.length,0,'Existing object URLs must survive attachment state changes');
fireEvent.click(ui.getByRole('button',{name:'Remove a.png'}));assert.deepEqual(revoked,['blob:preview-1']);
fireEvent.click(ui.getByRole('button',{name:'Send prompt'}));assert.equal(submissions[1][1].attachments.length,1);assert.equal(submissions[1][1].attachments[0].name,'b.png');assert.equal(revoked.length,2);
fireEvent.click(ui.getByRole('button',{name:'Use voice input'}));assert.match(ui.getByRole('status').textContent||'',/unavailable/);
cleanup();
const controlled=render(<PromptInput value="Controlled" onChange={v=>assert.equal(v,'')}/>);fireEvent.click(controlled.getByRole('button',{name:'Send prompt'}));cleanup();
console.log('Passed: submission metadata, Enter/Shift+Enter, controlled input, attachment cap/cleanup, unsupported voice status.');
