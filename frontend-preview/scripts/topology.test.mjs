import {JSDOM} from 'jsdom';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {window:w}=new JSDOM('<button id="theme-toggle" type="button"></button><div id="login-topology-background"></div>',{url:'http://localhost/login/',runScripts:'outside-only'});
w.eval(readFileSync('../login/theme.js','utf8'));
w.eval(readFileSync('../login/assets/login-background.js','utf8'));
await new Promise(resolve=>setTimeout(resolve,100));
const frame=w.document.querySelector('iframe');
assert(frame,'Login React effect mounted');
assert.equal(frame.dataset.mode,'dark');
assert.equal(frame.getAttribute('sandbox'),'allow-scripts');
assert.equal(frame.getAttribute('aria-hidden'),'true');
const source=frame.getAttribute('srcdoc');
const document=new JSDOM(source).window.document;
assert(document.querySelector('#animationCanvas'));
assert.equal(document.querySelectorAll('script[src],img,link[href]').length,0,'No external asset requests');
for(const script of document.querySelectorAll('script'))new Function(script.textContent);
assert.match(source,/prefers-reduced-motion/);
assert.match(source,/renderer.dispose/);
assert.match(source,/data-threeui-focus/);
console.log('PASS: login background mounts in dark mode, sandbox isolation, valid scene scripts, no external assets, motion and cleanup support');
w.document.getElementById('theme-toggle').click();
await new Promise(resolve=>setTimeout(resolve,50));
assert.equal(w.document.documentElement.dataset.continuumTheme,'light');
assert.equal(w.localStorage.getItem('continuum-theme'),'light');
assert.equal(frame.dataset.mode,'light');
assert.match(frame.getAttribute('srcdoc'),/filter:invert\(1\)/);
assert.equal(w.document.getElementById('theme-toggle').getAttribute('aria-label'),'Switch to dark theme');
w.document.getElementById('theme-toggle').click();
await new Promise(resolve=>setTimeout(resolve,50));
assert.equal(frame.dataset.mode,'dark');
assert.equal(w.localStorage.getItem('continuum-theme'),'dark');
assert.equal(w.document.getElementById('theme-toggle').getAttribute('aria-pressed'),'true');
console.log('PASS: dark/light toggle updates background and accessible label, persists preference, returns to dark');
w.close();
